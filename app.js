/* ==========================================================
   الرفيق | app.js
   الإصدار: 1.0.0

   المسؤولية:
   - تشغيل التطبيق.
   - تهيئة المكونات الأساسية.
   - تحميل الصفحة الأولى.
   - تطبيق الإعدادات العامة.
   - لا يحتوي على بيانات دينية.
==========================================================*/

"use strict";

const App = (() => {

    /*==========================================================
      حالة التطبيق
    ==========================================================*/

    let initialized = false;

    /*==========================================================
      تشغيل التطبيق
    ==========================================================*/

    function init() {

        if (initialized) {
            return;
        }

        initialized = true;

        applyLanguage();

        applyDirection();

        applyTheme();

        Router.init();

        console.log(
            `${CONFIG.APP_NAME} v${CONFIG.VERSION} started`
        );

    }

    /*==========================================================
      تطبيق اللغة
    ==========================================================*/

    function applyLanguage() {

        document.documentElement.lang = CONFIG.LANG;

    }

    /*==========================================================
      تطبيق الاتجاه
    ==========================================================*/

    function applyDirection() {

        document.documentElement.dir = CONFIG.DIR;

    }

    /*==========================================================
      تطبيق الثيم
    ==========================================================*/

    function applyTheme() {

        document.documentElement.setAttribute(
            "data-theme",
            CONFIG.DEFAULT_THEME
        );

    }

    /*==========================================================
      إعادة تشغيل
    ==========================================================*/

    function restart() {

        initialized = false;

        init();

    }

    /*==========================================================
      حالة التطبيق
    ==========================================================*/

    function isInitialized() {

        return initialized;

    }

    /*==========================================================
      الواجهة العامة
    ==========================================================*/

    return Object.freeze({

        init,

        restart,

        isInitialized

    });

})();

/*==========================================================
  بدء تشغيل التطبيق
==========================================================*/

document.addEventListener("DOMContentLoaded", () => {

    App.init();

});